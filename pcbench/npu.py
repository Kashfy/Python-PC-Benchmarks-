"""Cross-vendor NPU benchmarking through ONNX Runtime execution providers.

Every vendor reaches its neural accelerator through a different stack —
OpenVINO for Intel's AI Boost, Vitis AI for AMD's XDNA, QNN for Qualcomm's
Hexagon, DirectML for anything DX12, Core ML for Apple. ONNX Runtime sits above
all of them as *execution providers*, so one model and one loop can measure
whichever accelerator a machine actually has.

The methodology mirrors the Apple Neural Engine benchmark: no runtime reliably
reports where an operator ran, so the same model is timed on the CPU provider
and on each accelerator provider, and the **speedup is the evidence**. Below a
threshold the tool says the accelerator did not engage rather than presenting a
CPU number as an NPU result.

Requires ``onnxruntime`` (which brings numpy). Without it this module reports
``available: False`` and the run continues untouched — the model itself is
generated by :mod:`pcbench.onnx_model`, so the ``onnx`` package is not needed.
"""

from __future__ import annotations

import contextlib
import glob
import io
import os
import sys

from . import onnx_model

# --------------------------------------------------------------------------- #
# CUDA libraries shipped as pip wheels
# --------------------------------------------------------------------------- #
# `pip install onnxruntime-gpu[cuda,cudnn]` puts libcublas, libcudnn and the
# rest under `site-packages/nvidia/*/lib`, which is on no loader search path.
# ONNX Runtime then lists CUDAExecutionProvider as available, fails to dlopen
# its provider library, and silently falls back to the CPU — so the report says
# the accelerator did not engage when in fact the runtime could not find its
# own dependencies. PyTorch solves this by loading them itself at import time;
# so does this. Loading with RTLD_GLOBAL is what makes the symbols visible to
# the provider library that dlopens later.
#
# Harmless when the wheels are absent, when CUDA comes from the system instead,
# and on platforms that have no CUDA at all: it globs, finds nothing, returns.
_CUDA_WHEEL_DIRS = ("nvidia", "*", "lib")


def _preload_wheel_cuda() -> list[str]:
    """Load pip-installed CUDA libraries so ONNX Runtime can find them.

    Returns the libraries loaded, for diagnostics. Never raises: a machine
    without these wheels is the normal case.
    """
    if sys.platform == "darwin":
        return []
    try:
        import ctypes
        import site
        roots = list(site.getsitepackages())
        prefix = getattr(site, "getusersitepackages", None)
        if callable(prefix):
            roots.append(prefix())
    except Exception:
        return []

    loaded = []
    for root in roots:
        for directory in sorted(glob.glob(os.path.join(root,
                                                       *_CUDA_WHEEL_DIRS))):
            if os.name == "nt":
                try:
                    os.add_dll_directory(directory)
                except (OSError, AttributeError):
                    pass
                continue
            for lib in sorted(glob.glob(os.path.join(directory, "*.so*"))):
                try:
                    ctypes.CDLL(lib, mode=ctypes.RTLD_GLOBAL)
                    loaded.append(os.path.basename(lib))
                except OSError:
                    pass          # a stub, or a dependency not yet loaded
    return loaded


# Execution provider -> (label, vendor, kind, extra session options).
# `kind` separates true neural accelerators from GPUs so the report can say
# which is which.
_EP_INFO = {
    "CPUExecutionProvider":
        ("CPU", None, "cpu", None),
    "CoreMLExecutionProvider":
        ("Apple Neural Engine / GPU", "Apple", "npu", None),
    "OpenVINOExecutionProvider":
        ("Intel AI Boost NPU", "Intel", "npu", {"device_type": "NPU"}),
    "VitisAIExecutionProvider":
        ("AMD Ryzen AI NPU (XDNA)", "AMD", "npu", None),
    "QNNExecutionProvider":
        ("Qualcomm Hexagon NPU", "Qualcomm", "npu",
         {"backend_path": "QnnHtp.dll"}),
    "DmlExecutionProvider":
        ("DirectML device", None, "npu", None),
    "CUDAExecutionProvider":
        ("NVIDIA GPU (CUDA)", "NVIDIA", "gpu", None),
    "TensorrtExecutionProvider":
        ("NVIDIA GPU (TensorRT)", "NVIDIA", "gpu", None),
    "ROCMExecutionProvider":
        ("AMD GPU (ROCm)", "AMD", "gpu", None),
    "MIGraphXExecutionProvider":
        ("AMD GPU (MIGraphX)", "AMD", "gpu", None),
}

# Providers that exist but are not accelerators worth benchmarking.
_IGNORED = {"AzureExecutionProvider"}

# Minimum speedup over the CPU provider before we claim the accelerator ran.
ENGAGE_THRESHOLD = 1.5


def detect() -> dict:
    """Report ONNX Runtime availability and which providers are installed."""
    _preload_wheel_cuda()
    try:
        import onnxruntime as ort
    except Exception:
        return {"available": False,
                "note": "onnxruntime not installed; cross-vendor NPU "
                        "benchmarking unavailable "
                        "(pip install onnxruntime)"}
    # A provider that fails to load is reported by this module as a result;
    # ORT's own error log for it would otherwise land in the middle of the
    # benchmark report, in red, quoting C++ source paths.
    try:
        ort.set_default_logger_severity(4)          # fatal only
    except Exception:
        pass
    providers = [p for p in ort.get_available_providers()
                 if p not in _IGNORED]
    accelerators = [p for p in providers
                    if _EP_INFO.get(p, (None, None, "unknown", None))[2]
                    in ("npu", "gpu")]
    return {
        "available": True,
        "onnxruntime_version": ort.__version__,
        "providers": providers,
        "accelerator_providers": accelerators,
    }


@contextlib.contextmanager
def _quiet():
    """Swallow ONNX Runtime's own console output while a session is built.

    A provider that cannot load is a *result* here — the report says which
    accelerator did not engage and why. But ONNX Runtime also announces it
    itself, in red, with a C++ source path and a banner of asterisks, printed
    straight into the middle of the benchmark report. The C++ side is muted by
    the logger severity set in :func:`detect`; this catches the banner, which
    the Python layer prints directly.
    """
    sink = io.StringIO()
    with contextlib.redirect_stdout(sink), contextlib.redirect_stderr(sink):
        yield


def _bench_provider(model_path: str, provider: str, options,
                    batch: int, dim: int, seconds: float):
    """Time one execution provider. Returns (inferences_per_s, error)."""
    import numpy as np
    import onnxruntime as ort

    try:
        spec = [(provider, options)] if options else [provider]
        # Silence provider fallback chatter; a failure is caught below.
        so = ort.SessionOptions()
        so.log_severity_level = 3
        with _quiet():
            sess = ort.InferenceSession(model_path, sess_options=so,
                                        providers=spec)
        # ORT silently falls back to CPU when a provider cannot load, which
        # would otherwise be reported as an accelerator result.
        if provider not in sess.get_providers():
            return 0.0, f"{provider} did not load (fell back to CPU)"

        x = np.random.rand(batch, dim).astype(np.float32)
        feed = {"input": x}
        for _ in range(3):                       # warm up / graph compile
            sess.run(None, feed)

        from .core import clock
        start = clock()
        n = 0
        while clock() - start < seconds:
            sess.run(None, feed)
            n += 1
        elapsed = clock() - start
        return (n / elapsed if elapsed > 0 else 0.0), None
    except Exception as e:
        return 0.0, f"{type(e).__name__}: {str(e)[:160]}"


def run(seconds: float = 2.0, out_dir: str = ".") -> dict:
    """Benchmark every available accelerator provider against the CPU one."""
    info = detect()
    if not info.get("available"):
        return info

    try:
        model_path = onnx_model.write_model(
            os.path.join(out_dir, "npu_model.onnx"))
    except OSError as e:
        return {"available": True, "error": f"cannot write model: {e}"}

    batch, dim = onnx_model.DEFAULT_BATCH, onnx_model.DEFAULT_DIM
    flops = onnx_model.flops_per_inference()

    baseline, err = _bench_provider(model_path, "CPUExecutionProvider", None,
                                    batch, dim, seconds)
    if not baseline:
        return {"available": True,
                "error": f"CPU baseline failed: {err or 'no throughput'}"}

    devices = []
    for ep in info["accelerator_providers"]:
        label, vendor, kind, options = _EP_INFO.get(
            ep, (ep, None, "unknown", None))
        ips, err = _bench_provider(model_path, ep, options, batch, dim,
                                   seconds)
        entry = {
            "provider": ep, "label": label, "vendor": vendor, "kind": kind,
            "inferences_per_s": round(ips, 1),
            "gflops": round(ips * flops / 1e9, 1),
            "speedup_vs_cpu": round(ips / baseline, 2) if baseline else 0.0,
            "engaged": bool(ips and ips / baseline >= ENGAGE_THRESHOLD),
        }
        if err:
            entry["error"] = err
        devices.append(entry)

    best = max((d for d in devices if d["engaged"]),
               key=lambda d: d["inferences_per_s"], default=None)
    return {
        "available": True,
        "onnxruntime_version": info["onnxruntime_version"],
        "model": f"{onnx_model.DEFAULT_LAYERS}x MatMul+Relu, "
                 f"{dim}x{dim}, batch {batch}",
        "gflops_per_inference": round(flops / 1e9, 3),
        "cpu_inferences_per_s": round(baseline, 1),
        "cpu_gflops": round(baseline * flops / 1e9, 1),
        "devices": devices,
        "best_accelerator": best["label"] if best else None,
        "best_gflops": best["gflops"] if best else None,
    }


def extract_rates(payload: dict | None) -> dict:
    """Expose the fastest genuinely-engaged accelerator for scoring."""
    if not payload or not payload.get("available") or payload.get("error"):
        return {}
    engaged = [d for d in payload.get("devices", []) if d.get("engaged")]
    if not engaged:
        return {}
    best = max(engaged, key=lambda d: d.get("gflops", 0))
    return {"npu_onnx": float(best["gflops"])} if best.get("gflops") else {}
